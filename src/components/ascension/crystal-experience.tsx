  function speak(words: string, thenListen = true) {
    const serial = ++speechSerial.current;
    if (mutedRef.current) return;
    if (!("speechSynthesis" in window)) { setBackup(true); return; }
    recognition.current?.stop();
    const synthesis = window.speechSynthesis;
    synthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(words.slice(0, 1600));
    utterance.rate = 0.96;
    utterance.pitch = 1.01;
    // Only device-installed voices, never a browser's cloud TTS provider.
    const voices = synthesis.getVoices().filter(voice =>
      voice.lang.toLowerCase().startsWith("en") && voice.localService === true);
    const localVoice = voices.find(voice => /samantha|jenny|aria|zira|serena|ava|female/i.test(voice.name))
      ?? voices[0];
    if (!localVoice) {
      // Some browsers report zero voices until their local list loads.
      const retryWhenLoaded = () => {
        synthesis.removeEventListener("voiceschanged", retryWhenLoaded);
        if (speechSerial.current === serial) speak(words, thenListen);
      };
      synthesis.addEventListener("voiceschanged", retryWhenLoaded, { once: true });
      window.setTimeout(() => {
        synthesis.removeEventListener("voiceschanged", retryWhenLoaded);
        if (speechSerial.current !== serial) return;
        setBackup(true);
        setIssue("No installed on-device English voice is available; typed intent remains local.");
      }, 1500);
      return;
    }
    utterance.voice = localVoice;
    utterance.onstart = () => { if (speechSerial.current === serial) setSpeaking(true); };
    utterance.onend = () => {
      if (speechSerial.current !== serial) return;
      setSpeaking(false);
      if (thenListen && enteredRef.current && !workingRef.current) listen(true);
    };
    utterance.onerror = () => { if (speechSerial.current === serial) setSpeaking(false); };
    synthesis.speak(utterance);
  }
  function listen(automatic = false) {
    if (workingRef.current) return;
    const browser = window as Window & {
      SpeechRecognition?: new () => Recognition;
      webkitSpeechRecognition?: new () => Recognition;
    };
    const Ctor = browser.SpeechRecognition ?? browser.webkitSpeechRecognition;
    if (!Ctor) {
      setBackup(true);
      if (!automatic) setIssue("Speech recognition is unavailable here. You can type your intent.");
      return;
    }
    speechSerial.current++; // Cancelled utterances must never restart the microphone.
    recognition.current?.stop();
    window.speechSynthesis?.cancel();
    const mic = new Ctor();
    if (!("processLocally" in mic)) {
      setBackup(true);
      if (!automatic) setIssue("This browser does not support on-device speech recognition; typed intent stays private on your device.");
      return;
    }
    mic.processLocally = true;
    recognition.current = mic;
    mic.lang = "en-US";
    mic.continuous = false;
    mic.interimResults = false;
    mic.onresult = event => {
      const spoken = Array.from(event.results).at(-1)?.[0]?.transcript?.trim();
      if (spoken) processVoice.current(spoken);
    };
    mic.onerror = event => {
      if (recognition.current !== mic) return;
      setListening(false);
      if (event.error !== "no-speech" && event.error !== "aborted") {
        setIssue("Microphone: " + event.error);
        setBackup(true);
      }
    };
    mic.onend = () => { if (recognition.current === mic) { recognition.current = null; setListening(false); } };
    try { mic.start(); setListening(true); } catch {
      setListening(false); setBackup(true);
      if (!automatic) setIssue("Microphone could not start. You can type instead.");
    }
  }
