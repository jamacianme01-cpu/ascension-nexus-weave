import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const source = readFileSync(new URL("../src/lib/ascension/spoken-answer.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { interpretVoiceCommand, voiceCommandSpeech, briefSpokenAnswer } = await import("data:text/javascript;base64," + Buffer.from(compiled).toString("base64"));

assert.equal(interpretVoiceCommand("what is the blueprint for"), null);
assert.equal(interpretVoiceCommand("please explain how the rotor connects to the frame and the battery"), null);
assert.deepEqual(interpretVoiceCommand("Business Planner"), { kind: "section", section: "business" });
assert.deepEqual(interpretVoiceCommand("build"), { kind: "section", section: "build" });
assert.deepEqual(interpretVoiceCommand("engage"), { kind: "engage" });
assert.deepEqual(interpretVoiceCommand("next orb"), { kind: "next" });
assert.deepEqual(interpretVoiceCommand("previous pathway"), { kind: "previous" });
assert.deepEqual(interpretVoiceCommand("open the second orb"), { kind: "hear", target: 1 });
assert.deepEqual(interpretVoiceCommand("blend"), { kind: "hear", target: "blend" });
assert.deepEqual(interpretVoiceCommand("enter pathway"), { kind: "enter" });
assert.deepEqual(interpretVoiceCommand("blueprint"), { kind: "view", view: "blueprint" });
assert.deepEqual(interpretVoiceCommand("dissect"), { kind: "view", view: "dissect" });
assert.deepEqual(interpretVoiceCommand("explode"), { kind: "view", view: "exploded" });
assert.deepEqual(interpretVoiceCommand("open the picture"), { kind: "view", view: "picture" });
assert.deepEqual(interpretVoiceCommand("zoom in"), { kind: "zoom", direction: "in" });
assert.deepEqual(interpretVoiceCommand("rotate left"), { kind: "rotate", direction: "left" });
assert.deepEqual(interpretVoiceCommand("top view"), { kind: "camera", view: "top" });
assert.deepEqual(interpretVoiceCommand("move right"), { kind: "move", direction: "right" });
assert.deepEqual(interpretVoiceCommand("select the rotor"), { kind: "part", name: "rotor" });
assert.equal(voiceCommandSpeech({ kind: "view", view: "blueprint" }), "Opening the blueprint view.");
assert.ok(briefSpokenAnswer("one two three").length > 0);
const guide = readFileSync(new URL("../src/components/ascension/tree-guide.tsx", import.meta.url), "utf8");
assert.match(guide, /if \(previous === next\) return/);
assert.match(guide, /askRef\.current/);
assert.match(guide, /role="log"/);
console.log("PASS voice commands for orbs, views, and pictures; Tree follow-up is not aborted on the same turn");
